"""Regenerate the Rust ABI from the production Python contract (no game launch)."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'src'))
from sf_duel import spec

def generate():
    lines = ['// Generated by gpu/scripts/contract.py from src/sf_duel/spec.py.']
    for group in ('UNIT', 'SKILL', 'ITEM', 'TREE', 'PROJECTILE', 'GLOBAL', 'COMBAT_UNIT', 'COMBAT_PROJECTILE'):
        fields = getattr(spec, group + '_FIELDS')
        lines.append(f'pub const {group}_COUNT: usize = {len(fields)};')
        lines.append(f'pub const {group}_SCALES: [f32; {len(fields)}] = [' + ','.join(str(float(v)) for v in fields.values()) + '];')
        for i, name in enumerate(fields):
            lines.append(f'pub const {group}_{name.upper()}: usize = {i};')
    lines += [f'pub const GGD_SPEC_VERSION: usize = {spec.GGD_SPEC_VERSION};',
              'pub const ACTIONS: usize = 11;', 'pub const ITEMS: usize = 8;',
              'pub const BUYS: usize = 7;', 'pub const COORDS: usize = 129;',
              'pub const PREVIOUS: usize = 30;', 'pub const MEMORY: usize = 128;']
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    target = ROOT / 'gpu/src/contract.rs'
    content = generate()
    if '--check' in sys.argv:
        assert target.read_text() == content, 'Rust contract needs regeneration'
    else:
        target.write_text(content)
